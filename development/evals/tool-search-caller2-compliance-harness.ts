interface CapturedSearch {
  readonly runLabel: string;
  readonly rawQuery: string;
  readonly tsMs: number;
}

/**
 * Programmatic freshness check — see module doc's "The freshness assertion" section for why this
 * exists and why it must inspect a LIVE field value rather than grep source text. Reads the SAME
 * package `resolveMcpJsonInjection`'s spawned `jini-mcp` child actually imports at run time.
 * Aborts rather than silently running against stale/unexpected text.
 */
async function assertSchemaIsFresh(): Promise<void> {
  const mod = (await import("@jini-ai/mcp")) as {
    searchToolsTool?: { description?: string; inputSchema?: { properties?: { query?: { description?: string } } } };
  };
  const queryDescription = mod.searchToolsTool?.inputSchema?.properties?.query?.description ?? "";
  const staleExact = 'Keywords to search for, e.g. "navigate page" or "fill form". Required.';
  if (queryDescription === staleExact) {
    throw new Error(
      `[harness] ABORT: the LIVE search_tools.inputSchema.properties.query.description still equals the ` +
        `old stale value verbatim. This run would measure the conflicted (pre-eeb71733) state, not the ` +
        `coherent one — if that is actually what you want, remove this guard deliberately rather than ` +
        `silently proceeding. Otherwise rebuild @jini-ai/mcp first.`,
    );
  }
  if (queryDescription.length === 0) {
    throw new Error(`[harness] ABORT: could not read searchToolsTool.inputSchema.properties.query.description at all — resolution likely broken, not just stale.`);
  }
  console.log(`[harness] freshness check passed (live field value, not raw text): query description = "${queryDescription.slice(0, 80)}..."`);
}

async function main(): Promise<void> {
  await assertSchemaIsFresh();
  if (!process.env.TOVU_AGENT_DAEMON_TOKEN) {
    // Not enforced by this harness's own routes (loopback-only, nothing else can reach it), but
    // resolveMcpJsonInjection's credential() throws if unset, matching production's fail-closed
    // contract — set a throwaway value so the real code path executes unchanged.
    process.env.TOVU_AGENT_DAEMON_TOKEN = `harness-${randomUUID()}`;
  }

  const routeDeps = createRouteDeps(); // fully in-memory, pre-seeded — see module doc.
  const magicLinkPerEmailLimiter = createRateLimiter({ profile: MAGIC_LINK_PER_EMAIL, clock: routeDeps.clock });
  const surfaceExchanges = createSurfaceExchangeStore();

  const registry = createToolRegistry();
  for (const registration of buildAssistantToolRegistrations({ ...routeDeps, magicLinkPerEmailLimiter } as any, { surfaceExchanges })) {
    registry.register(registration);
  }
  const catalog = buildToolCatalogQuery(registry);

  const captured: CapturedSearch[] = [];
  let currentRunLabel = "(unset)";

  const app = express();
  app.use(express.json());
  // Logging tap ahead of the real route — captures the exact `q` the jini-mcp child sends, which
  // is exactly what the spawned CLI model composed as its `search_tools` `query` argument.
  // NOTE: this uses a single global `currentRunLabel`, so it is only correct for SEQUENTIAL runs —
  // do not parallelize case execution without keying captures by `runId` instead.
  app.use((req, _res, next) => {
    if (req.path === "/api/tools/search") {
      const q = typeof req.query.q === "string" ? req.query.q : "";
      captured.push({ runLabel: currentRunLabel, rawQuery: q, tsMs: Date.now() });
    }
    next();
  });

  const eventLog = createInMemoryEventLog();
  const lifecycle = createRunLifecycle({ eventLog });
  await lifecycle.rehydrate();

  const promptAugmenter: PromptAugmenter = {
    contextKinds: () => [],
    augmentUserRequest: ({ basePrompt }) => basePrompt,
    systemOverlay: () => REAL_SYSTEM_OVERLAY,
  };
  const agentExecutor = createAgentExecutor({
    lifecycle,
    mcpJsonInjection: resolveMcpJsonInjection(DAEMON_URL),
    promptAugmenter,
  });

  const principalByRunId = new Map<string, Principal>();

  // Trimmed copy of agent-daemon-server.ts's onStarted — same contract, minus attachment/frontend-
  // control handling this harness doesn't need. Same <<SUBAGENT_DISPATCH>> prefix, same contextRef
  // decode shape.
  const onStarted: RunStartHandler = ({ request, run, lifecycle: runLifecycle }) => {
    let prompt: string;
    let principal: Principal;
    try {
      const parsed = JSON.parse(request.contextRef) as { prompt?: unknown; principalId?: unknown };
      if (typeof parsed.prompt !== "string" || parsed.prompt.length === 0) throw new Error("bad prompt");
      if (typeof parsed.principalId !== "string" || parsed.principalId.length === 0) throw new Error("bad principalId");
      prompt = `<<SUBAGENT_DISPATCH>>\n\n${parsed.prompt}`;
      principal = { id: parsed.principalId };
    } catch (error) {
      void runLifecycle.finish({ runId: run.id, status: "failed", code: null, signal: null, resumable: false });
      console.error(`[harness] run ${run.id}: malformed contextRef`, error);
      return;
    }
    principalByRunId.set(run.id, principal);

    const cwd = mkdtempSync(join(tmpdir(), "tool-search-caller2-"));
    void agentExecutor
      .run({
        runId: run.id,
        agentId: "claude",
        prompt,
        cwd,
        permissionMode: "bypass",
      })
      .catch((error: unknown) => {
        console.error(`[harness] run ${run.id} failed to start`, error);
      });
  };

  registerRunRoutes(app, { lifecycle, onStarted }, { resolvedPortRef: { current: PORT } } as AdapterContext);
  registerToolCatalogRoutes(app, { catalog }, { resolvedPortRef: { current: PORT } } as AdapterContext);

  const server = app.listen(PORT, "127.0.0.1");
  await new Promise<void>((resolve, reject) => {
    server.once("listening", () => resolve());
    server.once("error", reject);
  });
  console.log(`[harness] scratch daemon listening on ${DAEMON_URL}`);

  const results: Array<{
    caseId: string;
    query: string;
    expect: string;
    startMs: number;
    endMs: number;
    status: string;
    searchToolsCalled: boolean;
    capturedQueries: string[];
  }> = [];

  for (const c of CASES) {
    currentRunLabel = c.id;
    const startMs = Date.now();
    console.log(`\n[harness] === case "${c.id}" === "${c.query}"`);
    const res = await fetch(`${DAEMON_URL}/api/runs`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        agentId: "claude",
        contextRef: JSON.stringify({ prompt: c.query, principalId: "harness-admin" }),
      }),
    });
    if (!res.ok) {
      console.error(`[harness] case "${c.id}": /api/runs POST failed`, res.status, await res.text());
      results.push({ caseId: c.id, query: c.query, expect: c.expect, startMs, endMs: Date.now(), status: "post-failed", searchToolsCalled: false, capturedQueries: [] });
      continue;
    }
    const body = (await res.json()) as { run?: { id?: string } };
    const runId = body.run?.id;
    if (!runId) {
      console.error(`[harness] case "${c.id}": no run id in response`, body);
      results.push({ caseId: c.id, query: c.query, expect: c.expect, startMs, endMs: Date.now(), status: "no-run-id", searchToolsCalled: false, capturedQueries: [] });
      continue;
    }

    const beforeCount = captured.length;
    let status = "timed-out";
    try {
      const terminal = await Promise.race([
        lifecycle.waitForTerminal(runId).then((s) => ({ ok: true as const, s })),
        new Promise<{ ok: false }>((resolve) => setTimeout(() => resolve({ ok: false }), RUN_TIMEOUT_MS)),
      ]);
      if (terminal.ok) {
        status = terminal.s.state;
      } else {
        console.warn(`[harness] case "${c.id}": exceeded ${RUN_TIMEOUT_MS}ms — cancelling`);
        await lifecycle.cancel({ runId, reason: "harness timeout" });
      }
    } catch (error) {
      status = `error: ${error instanceof Error ? error.message : String(error)}`;
    }

    const endMs = Date.now();
    const theseQueries = captured.slice(beforeCount).map((e) => e.rawQuery);
    console.log(`[harness] case "${c.id}": status=${status} durationMs=${endMs - startMs} search_tools calls=${theseQueries.length}`);
    for (const q of theseQueries) console.log(`         query: "${q}"`);
    results.push({
      caseId: c.id,
      query: c.query,
      expect: c.expect,
      startMs,
      endMs,
      status,
      searchToolsCalled: theseQueries.length > 0,
      capturedQueries: theseQueries,
    });
  }

  console.log("\n[harness] === SUMMARY ===");
  console.log(JSON.stringify(results, null, 2));

  server.close();
  process.exit(0);
}

main().catch((error) => {
  console.error("[harness] fatal", error);
  process.exit(1);
});
