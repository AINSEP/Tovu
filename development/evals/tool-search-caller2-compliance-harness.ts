/**
 * @file Caller-2 (spawned local CLI) real prompt-compliance harness for `search_tools`.
 *
 * Answers a question no prior tool-search eval in this directory answers: given a REAL, locally
 * spawned coding-agent CLI mid-task (not a dedicated blind expansion subagent), what query string
 * does it actually compose for `search_tools`, and does it comply with the descriptive-phrasing
 * instruction currently shipped?
 *
 * `search_tools` has exactly two callers in production — `src/assistant/byok-tool-surface.ts`
 * (the BYOK provider-model path) and `src/assistant/agent-daemon-server.ts` (the spawned-CLI path,
 * this harness). This harness targets the SECOND one. It is NOT the full production daemon, but it
 * reuses every component that actually shapes what the model sees: the real tool registry
 * (`buildAssistantToolRegistrations`), the real tool-catalog search routes (`@jini-ai/http-kit`'s
 * `registerToolCatalogRoutes`), the real `jini-mcp` MCP subprocess (via the real
 * `resolveMcpJsonInjection`, spawned fresh per run — so it reads whatever schema is ACTUALLY on
 * disk in `@jini-ai/mcp`'s built `dist/` at run time, not a mock), a real `AgentExecutor` spawning
 * a real local `claude` CLI, and the real system-overlay text copied verbatim from
 * `agent-daemon-server.ts`. It deliberately skips the bearer-auth gate (loopback-only scratch
 * server, nothing else can reach it), run-ownership, attachments, `page.*` frontend control, MCP
 * federation, and the SQLite audit sink — none of those influence how the model composes a
 * `search_tools` query.
 *
 * ## History and provenance (2026-08-05 session)
 *
 * Commit `0f397a4` changed `search_tools`'s description on BOTH callers from "keyword" phrasing to
 * descriptive phrasing. This harness's first 3 cases (the `id`s ending in `-copy`/`-queue`/`-list`
 * near the top of `CASES` below) were run as a pilot BEFORE the owner's separate fix
 * (`Jini` repo commit `eeb71733`, applied mid-session) — at that time, caller 2 actually carried a
 * live CONTRADICTION: the system overlay said "descriptive," but the `@jini-ai/mcp` tool schema
 * itself (a separate package, not touched by `0f397a4`) still said "by keyword" with literal
 * "navigate page"/"fill form" examples. A boundary check (wall-clock timestamps vs. the fix's
 * commit/build time) showed all 3 pilot runs actually landed AFTER the fix, so **no run in this
 * harness's history ever measured the genuinely conflicted state** — "which instruction wins" was
 * never actually tested, and remains an open question, not a resolved one. See
 * `ADS-memory/reports/analysis/2026-08-05-search-tools-real-compliance.md` for the full account,
 * including an unresolved discrepancy: the fix's own commit comment (`tool-catalog-tools.ts:44-48`)
 * claims the keyword schema used to win in production, which this harness has no data to confirm.
 *
 * The remaining 22 cases were run AFTER the fix, deliberately, as the n=25 coherent-state number
 * (25 = 3 + 22). All 25 results, with raw captured query strings, are committed alongside this file
 * in `tool-search-caller2-compliance-captures-2026-08-05.ts`.
 *
 * ## The freshness assertion — reusable beyond this experiment
 *
 * Two earlier attempts at "confirm the harness is measuring the state I think it's measuring" were
 * both false positives from grepping RAW SOURCE TEXT: `/keyword/i` matched the FIXED text's own
 * contrast language ("not a keyword bag", "terse keywords"); a follow-up exact-string check for the
 * old phrase then matched a **documentation comment the fix's own commit added**, quoting the old
 * string verbatim to explain the change ("This field previously read 'Keywords to search
 * for...'"). A comment written to prevent a future mistake caused one immediately. The only check
 * that cannot be fooled by a comment or by legitimate reuse of the trigger word is inspecting the
 * LIVE field value the running code actually uses — `import()` the real module and read the real
 * object, never grep source text for a staleness signal. See `assertSchemaIsFresh` below.
 *
 * ## Run
 *
 * `npx tsx development/evals/tool-search-caller2-compliance-harness.ts`
 * (from the Tovu repo root). Sequential — one live local `claude` CLI run per case, ~30-90s each.
 * Prints a `=== SUMMARY ===` JSON block at the end; the captures fixture file is the committed,
 * scoreable form of a prior run's output, not regenerated by running this again (running again
 * produces a FRESH result, which may legitimately differ — the CLI's own model/version, and the
 * model's non-determinism, are both unpinned by this harness; see the fixture file's own header).
 *
 * ## Safety
 *
 * Scratch port below is a placeholder — CONFIRM IT IS FREE before running (`lsof -nP -iTCP:<port>
 * -sTCP:LISTEN`) and never reuse a port this session's own record shows another agent or the
 * owner's dev tree already holds (commonly `3000`/`4319`/`5173` for the owner's live processes).
 * `TOVU_DB` is never set — `createRouteDeps()` is fully in-memory, single-process (this script IS
 * the only holder of the DB connection; the spawned `jini-mcp` child only ever talks HTTP to this
 * process), so the documented `TOVU_DB=memory` two-process/RBAC trap does not apply here.
 */
