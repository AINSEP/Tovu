/**
 * @file Canary for "query expansion / HyDE — rewrite the operator's phrasing into a hypothetical
 * tool description before searching."
 *
 * Run: `npx tsx development/evals/tool-search-hyde-canary.eval.ts`
 *
 * Canary question: does expanding the query help on the SAME held-out cases, and by how much per
 * model call? Scores the same held-out set twice — once with the operator's raw query, once with a
 * HyDE-expanded version of it — against both the current shipped index (with keywords) and the raw
 * baseline index (no keywords), so the delta HyDE contributes is visible on top of AND independent
 * of the already-shipped fix.
 *
 * BLIND BY CONSTRUCTION, mirroring how a real runtime HyDE call actually works: the model doing the
 * expansion never sees the index it's about to search, only the user's question plus general domain
 * knowledge. The expansions scored below (`tool-search-hyde-blind-expansions.ts`) were generated by
 * a fresh subagent given ONLY the 20 raw query strings and one paragraph of generic "this is a CMS
 * admin backend" context — it never saw the real tool catalog, `HELD_OUT_CASES`, or any eval file.
 * See that file's header for full provenance. This is the one canary in this set that did NOT need
 * a redo — it was built blind from the start, unlike canary 1.
 */
