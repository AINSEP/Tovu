const SEARCH_LIMIT = 10;

function fakeRouteDeps(): RouteDeps {
  const deps = {
    workspaceId: "ws-eval",
    clock: { nowIso: () => "2026-08-05T00:00:00.000Z" },
    idGen: { newId: () => "id-1" },
    authorize: async () => ({ allowed: true, reason: "matched" }),
    contentTypeRepo: {
      save: async () => {},
      appendRevision: async () => {},
      findByKey: async () => null,
      listByWorkspace: async () => [],
      transaction: async <T>(fn: () => Promise<T>) => fn(),
    },
    contentTypeIndexProvisioner: {
      provisionIndexesForNewContentType: async () => {},
      applyFieldIndexTransitions: async () => {},
      tearDownAllIndexesForContentType: async () => {},
    },
    outbox: { enqueue: async () => {} },
  };
  return deps as unknown as RouteDeps;
}

function score(catalog: ReturnType<typeof buildToolCatalogQuery>, cases: readonly EvalCase[], useHyde: boolean) {
  return cases.map((c) => {
    const acceptable = new Set<string>([c.expect, ...(c.alsoAcceptable ?? [])]);
    const searchText = useHyde ? (HYDE_EXPANSIONS[c.query] ?? c.query) : c.query;
    const hits = catalog.search(searchText, SEARCH_LIMIT);
    const index = hits.findIndex((h) => acceptable.has(h.id));
    return { query: c.query, expect: c.expect, rank: index === -1 ? null : index + 1, topHit: hits[0]?.id ?? "(no hits)" };
  });
}

function summarize(label: string, results: ReturnType<typeof score>) {
  const total = results.length;
  const top1 = results.filter((r) => r.rank === 1).length;
  const top3 = results.filter((r) => r.rank !== null && r.rank <= 3).length;
  const found = results.filter((r) => r.rank !== null).length;
  const pct = (n: number) => `${((n / total) * 100).toFixed(0)}%`.padStart(4);
  console.log(`  ${label.padEnd(28)} top-1 ${String(top1).padStart(2)}/${total} ${pct(top1)}   top-3 ${String(top3).padStart(2)}/${total} ${pct(top3)}   found ${String(found).padStart(2)}/${total} ${pct(found)}`);
}

function run(): void {
  const registry = buildEvalToolRegistry(fakeRouteDeps());
  const catalogWithKeywords = buildToolCatalogQuery(registry);
  const catalogNoKeywords = buildToolCatalogQuery(registry, { includeSearchKeywords: false });

  const missing = HELD_OUT_CASES.filter((c) => !HYDE_EXPANSIONS[c.query]);
  if (missing.length > 0) {
    console.error(`  WARNING: ${missing.length} held-out queries have no HyDE expansion:`);
    for (const m of missing) console.error(`    "${m.query}"`);
  }

  console.log(`\nCanary 4 — HyDE query expansion (blind), held-out set (n=${HELD_OUT_CASES.length})\n`);

  console.log(`  Against the RAW baseline index (no shipped keywords) — isolates HyDE's own contribution:`);
  summarize("raw query", score(catalogNoKeywords, HELD_OUT_CASES, false));
  summarize("HyDE-expanded query", score(catalogNoKeywords, HELD_OUT_CASES, true));

  console.log(`\n  Against the CURRENT shipped index (with tool-search-keywords.ts) — does HyDE add anything on top?`);
  const rawOnShipped = score(catalogWithKeywords, HELD_OUT_CASES, false);
  const hydeOnShipped = score(catalogWithKeywords, HELD_OUT_CASES, true);
  summarize("raw query", rawOnShipped);
  summarize("HyDE-expanded query", hydeOnShipped);

  console.log(`\n  Cases where HyDE changed the outcome (shipped index, raw vs HyDE):`);
  for (let i = 0; i < HELD_OUT_CASES.length; i++) {
    const r = rawOnShipped[i];
    const h = hydeOnShipped[i];
    if (r.rank !== h.rank) {
      console.log(`    "${r.query}"`);
      console.log(`        raw:  rank ${r.rank ?? "not found"} (top hit ${r.topHit})`);
      console.log(`        HyDE: rank ${h.rank ?? "not found"} (top hit ${h.topHit})`);
    }
  }

  console.log(`\n  Cost: one subagent call per query batch here (20 queries in one call, ~150-word budget each);`);
  console.log(`  a real runtime HyDE call would be one LLM call PER search_tools invocation, adding latency`);
  console.log(`  and cost to every turn that searches, not a one-time build-time cost like doc2query/keywords.\n`);
}

run();
