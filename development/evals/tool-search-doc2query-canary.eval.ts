function fakeRouteDeps(): RouteDeps {
  const deps = {
    workspaceId: "ws-eval",
    clock: { nowIso: () => "2026-08-05T00:00:00.000Z" },
    idGen: { newId: () => "id-1" },
    authorize: async () => ({ allowed: true, reason: "matched" }),
    contentTypeRepo: {
      save: async () => {},
      appendRevision: async () => {},
      findByKey: async () => null,
      listByWorkspace: async () => [],
      transaction: async <T>(fn: () => Promise<T>) => fn(),
    },
    contentTypeIndexProvisioner: {
      provisionIndexesForNewContentType: async () => {},
      applyFieldIndexTransitions: async () => {},
      tearDownAllIndexesForContentType: async () => {},
    },
    outbox: { enqueue: async () => {} },
  };
  return deps as unknown as RouteDeps;
}

function sourceForToolId(id: string): string {
  const [prefix] = id.split("_");
  return prefix && prefix.length > 0 ? prefix : "tovu";
}

function score(db: Database.Database, cases: readonly EvalCase[]) {
  return cases.map((c) => {
    const acceptable = new Set<string>([c.expect, ...(c.alsoAcceptable ?? [])]);
    const hits = searchToolCatalog(db, c.query, 10);
    const index = hits.findIndex((h) => acceptable.has(h.id));
    return { query: c.query, expect: c.expect, rank: index === -1 ? null : index + 1, topHit: hits[0]?.id ?? "(no hits)" };
  });
}

function summarize(label: string, results: ReturnType<typeof score>) {
  const total = results.length;
  const top1 = results.filter((r) => r.rank === 1).length;
  const top3 = results.filter((r) => r.rank !== null && r.rank <= 3).length;
  const found = results.filter((r) => r.rank !== null).length;
  const pct = (n: number) => `${((n / total) * 100).toFixed(0)}%`.padStart(4);
  console.log(`  ${label.padEnd(12)} top-1 ${String(top1).padStart(2)}/${total} ${pct(top1)}   top-3 ${String(top3).padStart(2)}/${total} ${pct(top3)}   found ${String(found).padStart(2)}/${total} ${pct(found)}`);
}

function run(): void {
  const registry = createToolRegistry();
  for (const registration of buildAssistantToolRegistrations(fakeRouteDeps())) registry.register(registration);
  const descriptors = registry.list();

  const db = new Database(":memory:");
  ensureToolCatalogTables(db);
  reseedToolCatalog(
    db,
    descriptors.map((d) => {
      const questions = DOC2QUERY[d.id];
      const description = questions ? `${d.description ?? ""} — ${questions.join(" ")}` : (d.description ?? "");
      return { id: d.id, description, inputSchema: d.inputSchema, source: sourceForToolId(d.id) };
    }),
  );

  const coverage = descriptors.filter((d) => DOC2QUERY[d.id]).length;
  console.log(`\nCanary 1 — doc2query synthetic questions (BLIND, subagent-generated) vs. hand-written keywords`);
  console.log(`  doc2query coverage: ${coverage}/${descriptors.length} tools (full catalog)\n`);

  const heldOut = score(db, HELD_OUT_CASES);
  console.log(`  doc2query HELD-OUT:`);
  summarize("held-out", heldOut);
  console.log(`\n  compare to current keywords HELD-OUT (from tool-search-quality.eval.ts): top-1 9/20 45%   top-3 11/20 55%   found 14/20 70%\n`);

  const missed = heldOut.filter((r) => r.rank === null);
  if (missed.length > 0) {
    console.log(`  doc2query held-out misses:`);
    for (const m of missed) console.log(`    "${m.query}" wanted ${m.expect}, got ${m.topHit}`);
  }
  console.log("");
}

run();
