/**
 * @file Canary for "doc2query — generate synthetic questions per tool instead of hand-written
 * keywords."
 *
 * Run: `npx tsx development/evals/tool-search-doc2query-canary.eval.ts`
 *
 * `tool-search-keywords.ts` already proved the mechanism (missing vocabulary, not ranking, is the
 * bottleneck) by hand-writing bag-of-words synonyms per tool. This canary asks whether a SYSTEMATIC
 * generation process — 5 natural-language questions per tool, generated from the tool's id and
 * description alone — beats that hand-written list on the same held-out set. If yes, doc2query is a
 * process change (generate at build time from the descriptor, no per-tool human judgment call)
 * rather than a ranking change; if it's roughly a wash, the existing keywords file is simpler and
 * should stay.
 *
 * BLIND BY CONSTRUCTION. A first attempt at this canary was written inline by the dispatching agent
 * and scored 90% top-1 — and was THROWN OUT, because that agent had already read `HELD_OUT_CASES` to
 * build the other canaries and, despite trying not to, produced several near-verbatim lifts of
 * held-out query text (e.g. wrote "Is anything wrong with the data store?" for `database_get_health`
 * — not a paraphrase, the held-out query itself). Full writeup in the "Canary 1" section of
 * `ADS-memory/reports/analysis/2026-08-05-tool-search-canaries.md`. The questions scored below
 * (`tool-search-doc2query-blind-questions.ts`) were instead generated by a FRESH subagent that was
 * given only the 131-tool catalog and explicitly never saw the held-out set or any eval file — see
 * that file's header for the exact provenance. Full catalog coverage (131/131), not a subset, since
 * a blind subagent pass costs the same either way.
 */
