// The sweep
// ---------------------------------------------------------------------------

export interface SweepOptions {
  readonly repoRoot: string;
  /** repo-relative, forward-slash paths of the files to sweep */
  readonly files: readonly string[];
  /** when false, `repo-relative-string` references are not collected for that file (see
   *  `shouldScanStringsIn` for the rule and its rationale) */
  readonly scanStrings?: (repoRelativeFile: string) => boolean;
  readonly segments?: ReadonlySet<string>;
}

/**
 * Path strings inside a `*.test.ts` / `*.test.mjs` file are FIXTURE DATA, not references the
 * program follows — a coverage-gate test legitimately asserts against `src/contracts/.../marker.ts`
 * that has never existed. Their relative IMPORTS are still swept (class 1), because those really do
 * have to resolve. Stated as a rule rather than left to an allowlist of individual strings.
 */
export function shouldScanStringsIn(repoRelativeFile: string): boolean {
  return !/\.(test|spec)\.(ts|tsx|mts|mjs|cjs|js)$/.test(repoRelativeFile);
}

/**
 * Resolves every path reference in `files` and returns the ones that resolve to nothing.
 *
 * @param options repo root, the file list, and optional overrides for string-scanning and the
 *        derived segment set (the latter injectable so a test can drive the matcher deterministically)
 * @returns findings ordered by file then line; empty means every reference resolves
 * @complexity O(F · n) in file count and file size, plus one `existsSync` per candidate target.
 */
export function sweepFiles(options: SweepOptions): readonly DeadPathFinding[] {
  const { repoRoot, files } = options;
  const scanStrings = options.scanStrings ?? shouldScanStringsIn;
  const segments = options.segments ?? collectRepoSegments(repoRoot);
  const findings: DeadPathFinding[] = [];

  for (const file of files) {
    findings.push(...sweepOneFile(repoRoot, file, segments, scanStrings(file)));
  }

  return findings.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
}

/**
 * All three reference classes for a single file: relative imports, hardcoded repo-relative
 * strings, and (2026-09-03) the trailing literal segments of `path.join`/`path.resolve` calls.
 *
 * @param repoRoot absolute repository root
 * @param file repo-relative path of the file to read
 * @param segments the derived repo-segment set
 * @param scanStrings whether class-2/class-3 hardcoded path references should be collected for
 *        this file (same rationale for both: a test file's fixture data is not a real reference —
 *        see `shouldScanStringsIn`)
 * @returns the dead references found, in the order they were checked
 * @complexity O(n) in file size, plus one `existsSync` per candidate target.
 */
function sweepOneFile(
  repoRoot: string,
  file: string,
  segments: ReadonlySet<string>,
  scanStrings: boolean
): readonly DeadPathFinding[] {
  const abs = path.join(repoRoot, file);
  const source = fs.readFileSync(abs, "utf8");
  const imports = extractRelativeImportSpecifiers(source);
  const findings: DeadPathFinding[] = [];

  for (const { specifier, line } of imports) {
    const candidates = resolveImportCandidates(abs, specifier);
    if (candidates.some((c) => fs.existsSync(c))) continue;
    findings.push({
      file,
      line,
      kind: "relative-import",
      specifier,
      attempted: candidates.map((c) => toRepoRelative(repoRoot, c)),
    });
  }

  if (!scanStrings) return findings;

  const ownImportSpecifiers = new Set(imports.map((i) => i.specifier));
  for (const { value, line } of extractStringLiterals(source)) {
    const classified = classifyRepoRelativeString(value, { knownRepoSegments: segments, ownImportSpecifiers });
    if (classified.kind !== "repo-relative-path") continue;
    const required = pathThatMustExist(classified.repoRelative);
    if (fs.existsSync(path.join(repoRoot, required))) continue;
    findings.push({ file, line, kind: "repo-relative-string", specifier: value, attempted: [required] });
  }

  for (const { segments: rawSegments, line } of extractPathJoinSegments(source)) {
    const meaningful = dropLeadingParentSegments(rawSegments, fileDirectoryDepth(file));
    if (meaningful === null) continue; // ".." count doesn't reach exactly to repo root - can't classify safely
    if (meaningful.length < 1) continue; // nothing left but ".." segments - no target to check
    const classified = classifyPathJoinSegments(meaningful, { knownRepoSegments: segments, ownImportSpecifiers });
    if (classified.kind !== "repo-relative-path") continue;
    const required = pathThatMustExist(classified.repoRelative);
    if (fs.existsSync(path.join(repoRoot, required))) continue;
    findings.push({ file, line, kind: "path-join-call", specifier: classified.repoRelative, attempted: [required] });
  }

  return findings;
}

/** Stable "file:line specifier" key for comparing a finding against the known-broken register. */
export const findingKey = (f: PathReference): string => `${f.file}:${f.specifier}`;

/**
 * Every `*.ts` file under `development/scripts/` and `development/evals/`, plus the `*.config.ts`
 * files in the db tooling directory — the places the restructure left dead paths in (most of the
 * 2026-09-05 breaks lived under `development/evals/`, which this sweep had never covered).
 * Enumerated from disk rather than listed, so a new script or eval is swept the day it lands.
 *
 * @complexity O(d) in files under the three roots.
 */
export function collectSweepTargets(repoRoot: string): readonly string[] {
  const out: string[] = [];

  const walk = (relDir: string): void => {
    const abs = path.join(repoRoot, relDir);
    for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
      if (entry.name.startsWith(".") && entry.name !== "__tests__") continue;
      const rel = `${relDir}/${entry.name}`;
      if (entry.isDirectory()) {
        if (entry.name === "node_modules" || entry.name === "fixtures") continue;
        walk(rel);
      } else if (entry.name.endsWith(".ts")) {
        out.push(rel);
      }
    }
  };

  walk("development/scripts");
  walk("development/evals");

  const dbDir = "apps/website/src/platform/db";
  for (const entry of fs.readdirSync(path.join(repoRoot, dbDir), { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith(".config.ts")) out.push(`${dbDir}/${entry.name}`);
  }

  return out.sort();
}
