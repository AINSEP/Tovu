/**
 * Replaces every comment in TypeScript/JavaScript source with spaces, preserving byte offsets and
 * line breaks so downstream line numbers stay accurate.
 *
 * Hand-written state machine rather than a regex: a regex cannot tell a `//` inside a string
 * literal from a real comment, and this file's whole job is reading string literals correctly. It
 * tracks single/double-quoted strings, template literals (including nested `${}` interpolation
 * depth), and both comment forms.
 *
 * Regex literals are NOT tracked. A regex containing an unbalanced quote or a `//` sequence would
 * confuse the scanner — accepted deliberately, because a confused scanner produces a spurious
 * finding at a specific line that a human then reads, whereas the alternative (a real JS lexer with
 * ASI-aware regex/division disambiguation) is far more machinery than this guard warrants. No file
 * in the current sweep scope trips it; `sweepFiles` failing loudly on one is the intended outcome.
 *
 * @param source raw file text
 * @returns text of identical length with comment bytes replaced by spaces (newlines kept)
 * @complexity O(n) time in source length, O(1) auxiliary space beyond the output buffer.
 * @tradeoffs Cyclomatic complexity 26, over this repo's ceiling of 9, and deliberately left whole.
 * The branches ARE the state-transition table of a character scanner; splitting them across helpers
 * hides which transitions exist and makes the lexer harder to verify, not easier. Nesting stays at
 * one or two levels throughout. `development/scripts/**` is outside `check:src-complexity-drift`'s
 * scan scope, so this is a disclosed deviation rather than a suppressed gate failure.
 */
export function stripComments(source: string): string {
  const out = source.split("");
  const templateStack: number[] = [];
  let i = 0;
  let state: "code" | "single" | "double" | "template" | "line-comment" | "block-comment" = "code";

  const blank = (from: number, to: number): void => {
    for (let k = from; k < to; k++) if (out[k] !== "\n") out[k] = " ";
  };

  while (i < source.length) {
    const c = source[i];
    const next = source[i + 1];

    if (state === "code") {
      if (c === "/" && next === "/") {
        const start = i;
        while (i < source.length && source[i] !== "\n") i++;
        blank(start, i);
        continue;
      }
      if (c === "/" && next === "*") {
        const start = i;
        i += 2;
        while (i < source.length && !(source[i] === "*" && source[i + 1] === "/")) i++;
        i = Math.min(i + 2, source.length);
        blank(start, i);
        continue;
      }
      if (c === "'") state = "single";
      else if (c === '"') state = "double";
      else if (c === "`") {
        state = "template";
        templateStack.push(0);
      } else if (c === "}" && templateStack.length > 0) {
        // closing a `${ ... }` interpolation returns us to the enclosing template literal
        state = "template";
      }
      i++;
      continue;
    }

    if (c === "\\") {
      i += 2;
      continue;
    }

    if (state === "single" && c === "'") state = "code";
    else if (state === "double" && c === '"') state = "code";
    else if (state === "template") {
      if (c === "`") {
        state = "code";
        templateStack.pop();
      } else if (c === "$" && next === "{") {
        state = "code";
        i += 2;
        continue;
      }
    }
    i++;
  }

  return out.join("");
}

/** 1-based line number of a byte offset. */
function lineOf(source: string, offset: number): number {
  let line = 1;
  for (let i = 0; i < offset && i < source.length; i++) if (source[i] === "\n") line++;
  return line;
}

