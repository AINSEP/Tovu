export type ReferenceKind = "relative-import" | "repo-relative-string" | "path-join-call";

export interface PathReference {
  /** repo-relative, forward-slash path of the file the reference was written in */
  readonly file: string;
  /** 1-based line number within that file */
  readonly line: number;
  readonly kind: ReferenceKind;
  /** the specifier exactly as written in source */
  readonly specifier: string;
}

export interface DeadPathFinding extends PathReference {
  /** repo-relative candidate targets that were probed, all of which were absent */
  readonly attempted: readonly string[];
}

/**
 * Every named reason the sweep declines to treat a slash-bearing string literal as a filesystem
 * path. Exposed so the test can assert the ruleset by name and so a report can say WHICH rule
 * skipped a given string rather than "it didn't match".
 */
export type SkipReason =
  | "url-scheme"
  | "glob-or-regex-metacharacter"
  | "contains-whitespace"
  | "package-imports-specifier"
  | "scoped-package-specifier"
  | "absolute-or-home-path"
  | "no-path-separator"
  | "colon-bearing-specifier"
  | "parent-relative-outside-repo"
  | "trailing-separator"
  | "own-import-specifier"
  | "not-a-known-repo-segment";

export type StringClassification =
  | { readonly kind: "repo-relative-path"; readonly repoRelative: string }
  | { readonly kind: "skipped"; readonly reason: SkipReason };

export interface StringToken {
  /** the literal's text with the quotes removed and escapes left as written */
  readonly value: string;
  /** 1-based line the literal opens on */
  readonly line: number;
  /** true for a backtick literal (interior never re-scanned; see `tokenizeStringLiterals`) */
  readonly isTemplate: boolean;
  /** code text immediately preceding the opening quote, trimmed — used to tell an import specifier
   *  from any other literal */
  readonly precedingCode: string;
}

/** Matches the tail of the code preceding a string literal when that literal is a module specifier:
 *  `from "x"`, `import "x"`, `import("x")`, `require("x")`. */
const IMPORT_POSITION = /(?:\bfrom|\bimport|\brequire)\s*\(?\s*$/;

/**
 * Splits comment-stripped source into its TOP-LEVEL string literals — literals written in code, not
 * ones nested inside another literal's text.
 *
 * The nesting distinction is the whole reason this is a tokenizer and not a regex. A regex for
 * `from "…"` matches the *text* of `'import { a } from "./a.js";'` and of a template literal holding
 * a source-code fixture, and reports the fixture's paths as real dead imports — which is exactly what
 * a regex-based first draft of this file did to its own test. A literal's interior is consumed whole
 * and never re-scanned, so embedded source code is inert.
 *
 * Template literals are tokenized (so their interiors stay inert) but their `${}` interpolations are
 * skipped along with the rest of the body: a specifier written inside an interpolation would be
 * missed. No file in scope does that, and an interpolated specifier is not a fixed path anyway.
 *
 * @param source raw file text
 * @returns the literals in source order, each with its line and preceding code context
 * @complexity O(n) time in source length.
 * @tradeoffs Cyclomatic complexity 15, over the ceiling of 9, for the same reason as
 * `stripComments`: this is a scanner's transition table, not accidental branching.
 */
export function tokenizeStringLiterals(source: string): readonly StringToken[] {
  const code = stripComments(source);
  const tokens: StringToken[] = [];
  let i = 0;
  let lastCodeEnd = 0;

  while (i < code.length) {
    const quote = code[i];
    if (quote !== "'" && quote !== '"' && quote !== "`") {
      i++;
      continue;
    }
    const open = i;
    i++;
    let depth = 0;
    while (i < code.length) {
      const c = code[i];
      if (c === "\\") {
        i += 2;
        continue;
      }
      if (quote === "`") {
        if (c === "$" && code[i + 1] === "{") {
          depth++;
          i += 2;
          continue;
        }
        if (c === "}" && depth > 0) {
          depth--;
          i++;
          continue;
        }
      } else if (c === "\n") {
        break; // unterminated single/double-quoted literal — do not run past the line
      }
      if (c === quote && depth === 0) break;
      i++;
    }
    const close = i;
    tokens.push({
      value: code.slice(open + 1, close),
      line: lineOf(code, open),
      isTemplate: quote === "`",
      precedingCode: code.slice(lastCodeEnd, open).trimEnd(),
    });
    i = close + 1;
    lastCodeEnd = i;
  }

  return tokens;
}

/**
 * Extracts every relative import specifier (`./…`, `../…`) written in a source file.
 *
 * Bare specifiers (`node:fs`, `drizzle-kit`, `@jini-ai/cms`) are omitted on purpose: those resolve
 * through `node_modules`/`package.json#imports`, not the repo tree, so their existence is npm's
 * problem and not a restructure-rot symptom.
 *
 * @param source raw file text
 * @returns specifier strings paired with the 1-based line they appear on, in source order
 * @complexity O(n) in source length.
 */
export function extractRelativeImportSpecifiers(source: string): readonly { specifier: string; line: number }[] {
  return tokenizeStringLiterals(source)
    .filter((t) => !t.isTemplate)
    .filter((t) => t.value.startsWith("./") || t.value.startsWith("../"))
    .filter((t) => IMPORT_POSITION.test(t.precedingCode))
    .map((t) => ({ specifier: t.value, line: t.line }));
}

/**
 * Extracts every top-level single/double-quoted string literal.
 *
 * Template literals are excluded from the class-2 candidate set: an interpolated one is not a fixed
 * path, and this codebase writes no fixed path with backticks.
 */
export function extractStringLiterals(source: string): readonly { value: string; line: number }[] {
  return tokenizeStringLiterals(source)
    .filter((t) => !t.isTemplate)
    .map((t) => ({ value: t.value, line: t.line }));
}

