// Resolution
// ---------------------------------------------------------------------------

/**
 * Candidate on-disk targets for one ESM import specifier, applying this codebase's `.js`-written /
 * `.ts`-on-disk extension rewrite.
 *
 * `import "./route-coverage-lib.js"` is satisfied by `route-coverage-lib.ts` under `tsx`, so a
 * resolver that only probed the literal `.js` would report every correct import in the repo as
 * dead. Directory and extensionless forms are probed too, since a few `.mjs` scripts use them.
 *
 * @param importerAbsPath absolute path of the file containing the import
 * @param specifier the relative specifier as written
 * @returns absolute candidate paths, most-likely first
 * @complexity O(1) — a fixed candidate list.
 */
export function resolveImportCandidates(importerAbsPath: string, specifier: string): readonly string[] {
  const base = path.resolve(path.dirname(importerAbsPath), specifier);
  const candidates: string[] = [base];

  const jsLike = /\.(js|mjs|cjs)$/.exec(base);
  if (jsLike) {
    const stem = base.slice(0, -jsLike[0].length);
    candidates.push(`${stem}.ts`, `${stem}.tsx`, `${stem}.mts`, `${stem}.cts`, `${stem}.d.ts`);
  } else if (!path.extname(base)) {
    candidates.push(`${base}.ts`, `${base}.tsx`, `${base}.js`, `${base}.mjs`, `${base}.cjs`);
    candidates.push(path.join(base, "index.ts"), path.join(base, "index.js"), path.join(base, "index.mjs"));
  }
  return candidates;
}

const toRepoRelative = (repoRoot: string, abs: string): string =>
  path.relative(repoRoot, abs).split(path.sep).join("/");

