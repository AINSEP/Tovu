/**
 * @file Dead-path sweep — resolves every filesystem path reference in the repo's tooling files and
 * reports the ones that point at nothing.
 *
 * ## Why this exists
 *
 * The `apps/website` restructure (2026-09) moved the source tree but left hardcoded `src/...` paths
 * behind in tooling that nothing exercises. Every instance was invisible until someone happened to
 * run the tool. The six known when this file was written (the first two since repaired, the last
 * four repaired in 921d705f):
 *
 * | file | consequence |
 * |---|---|
 * | `apps/website/src/platform/db/drizzle.config.ts` | `drizzle-kit generate` failed "No schema files found" — NO migration could be generated by anyone |
 * | `apps/website/src/platform/db/drizzle.database-journal.config.ts` | same, for the sidecar `ops/database-journal.db` target |
 * | `development/scripts/generate-seed-content.ts` | `check:seed-content-drift` crashed; CI's `continue-on-error: true` swallowed it |
 * | `development/scripts/list-server-test-files.ts` | prints nothing, so `test:cov:server:{unit,integration}` expand to an EMPTY file list |
 * | `development/scripts/backfill-vendor-credentials.ts` | its test never ran |
 * | `development/scripts/backfill-slug-collision-defaults.ts` | its test never ran |
 *
 * A type-checker cannot see any of them: four are string literals, and the two import cases only
 * fail at module-resolution time in a script `tsc` never loads.
 *
 * ## The two reference classes, and the two different resolution bases
 *
 * 1. **Relative import specifiers** (`./x`, `../y` in `import`/`export ... from`, dynamic
 *    `import()`, `require()`) resolve against the IMPORTING FILE'S directory, with this codebase's
 *    ESM `.js`-written/`.ts`-on-disk extension rewrite applied.
 * 2. **Hardcoded repo-relative path strings** resolve against the CWD the npm script runs in — the
 *    REPO ROOT — not the containing file's directory. `drizzle.config.ts`'s own header comment
 *    documents this explicitly, and it is why that file legitimately reads
 *    `"./apps/website/src/platform/db/schema.sqlite.ts"` from inside `apps/website/src/platform/db/`.
 *    `list-server-test-files.ts`'s `execFileSync("find", ["src/server", ...])` is the same class.
 *
 * Class 2 is the one a naive "check the imports" linter misses entirely, and it is three of those six
 * instances (both drizzle configs and `list-server-test-files.ts`). Across the whole current sweep the
 * split is 15 dead strings to 20 dead imports — neither class is a rounding error.
 *
 * ## Precision over recall, deliberately
 *
 * Scanning string literals for "things that look like paths" over-matches: globs, URLs, mime types,
 * Node package-imports subpath specifiers, npm package names, and prose all contain slashes. Every
 * exclusion below is a NAMED rule (`SkipReason`) reported alongside the finding rather than a silent
 * drop, so a future reader can see exactly what the sweep declines to look at and challenge it. The
 * sweep is allowed to miss a real dead path; it is not allowed to cry wolf, because a guard with
 * false positives gets an allowlist and an allowlist rots.
 */
