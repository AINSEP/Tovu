/** Zips one locale's list onto the English keys; a length mismatch throws at load, never leaks English. */
function toDictionary(strings: readonly string[]): Record<string, string> {
  if (strings.length !== ROUTINES_KEYS.length) throw new Error(`routines-i18n: expected ${ROUTINES_KEYS.length} strings, got ${strings.length}`);
  return Object.fromEntries(ROUTINES_KEYS.map((key, index) => [key, strings[index] as string]));
}

