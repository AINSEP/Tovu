/** Real operator/member session owners: a member bearer cannot reach an admin plugin route. */
import '../../../../../../platform/site-dir/__tests__/helpers/isolated-catalog-home.js';
import assert from 'node:assert/strict';
import test from 'node:test';
import { createHash } from 'node:crypto';
import express from 'express';
import { createPluginContributionCapture, type PluginManifest } from '@jini-ai/plugins/host';
import { createRouteDeps } from '../../../../../runtime/composition/app.js';
import { registerAuthRoutes } from '../../../../admin-http/dev-auth.js';
import { parsePublicJsonBody } from '../../../../shared/json-body-parsers.js';
import { bootAuthenticated, loginAsBarePrincipal } from '../../../../../__tests__/helpers/http-test-server.js';
import { MEMBER_SESSION_COOKIE } from '../../members/complete-sign-in.js';
import { registerPluginContributionRoutes, createPluginRouteAuthPorts } from '../../plugin-contributions.js';
test('host authenticates real member and operator cookies independently, including revocation and disabled members', async t => {
  const deps = createRouteDeps();
  const id = 'auth-sample';
  const manifest: PluginManifest = { id, name:'Auth Sample', version:'0.1.0', sdkRange:'*', engine:1, tier:'tier-3', capabilities:['http.route.register'],hooks:[],fields:[],integrity:{},contributes:{routes:['POST /public','POST /member','POST /admin']} };
  const capture = createPluginContributionCapture({manifest});
  for (const access of ['public','member','admin'] as const) capture.routes.add({method:'POST',path:`/${access}`,access,handler:async ({auth,body})=>({body:{auth,body}})});
  assert.ok(deps.pluginContributions);
  deps.pluginContributions.replace({contributions:capture.seal({sdk:{} as never})});
  await deps.pluginActivationRepo.save({pluginId:id,workspaceId:deps.workspaceId,version:manifest.version,enabled:true,updatedAt:deps.clock.nowIso()});
  const app = express(); app.use(parsePublicJsonBody); registerAuthRoutes(app,deps);
  registerPluginContributionRoutes({app,deps,auth:createPluginRouteAuthPorts({deps})});
  const {baseUrl,cookie:operatorCookie} = await bootAuthenticated(app,t);
  const memberId = 'plugin-member'; const token = 'member-secret'; const now = deps.clock.nowIso();
  const member = {id:memberId,workspaceId:deps.workspaceId,email:'member@example.com',status:'active' as const,createdAt:now,updatedAt:now,version:1};
  await deps.memberRepo.save(member);
  const session = {id:'plugin-member-session',workspaceId:deps.workspaceId,memberId,tokenHash:createHash('sha256').update(token).digest('hex'),createdAt:now,expiresAt:new Date(Date.parse(now)+600000).toISOString()};
  await deps.memberSessionRepo.save(session);
  const memberCookie = `${MEMBER_SESSION_COOKIE}=${token}`;
  const call = (access: string,cookie = '')=>fetch(`${baseUrl}/api/p/${id}/${access}`,{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({payload:true})});
  assert.equal((await call('public')).status,200);
  assert.equal((await call('member')).status,401);
  assert.equal((await call('admin')).status,401);
  assert.equal((await call('member',operatorCookie)).status,401);
  assert.equal((await call('admin',memberCookie)).status,401);
  const memberResponse = await call('member',memberCookie); assert.equal(memberResponse.status,200);
  assert.equal((await memberResponse.json()).auth.principalId,memberId);
  assert.equal((await call('admin',operatorCookie)).status,200);
  const bareCookie = await loginAsBarePrincipal(deps,baseUrl);
  assert.equal((await call('admin',bareCookie)).status,403);
  await deps.memberRepo.save({...member,status:'disabled',version:2});
  assert.equal((await call('member',memberCookie)).status,401);
  await deps.memberRepo.save({...member,status:'active',version:3});
  await deps.memberSessionRepo.save({...session,revokedAt:now});
  assert.equal((await call('member',memberCookie)).status,401);
  assert.equal((await call('admin',operatorCookie)).status,200);
});
