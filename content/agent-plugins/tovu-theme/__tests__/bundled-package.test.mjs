import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import { packAgentPluginDirectory } from '../../../../apps/website/src/features/agent-plugins/lifecycle.ts';

test('the theme package ships its v2 contract and teaches native tool authoring', async () => {
  const root = path.resolve(import.meta.dirname, '..');
  const packed = await packAgentPluginDirectory(root);
  assert.ok(packed.files.includes('skills/tovu-theme/references/theme-v2-contract.md'));
  assert.ok(packed.files.includes('skills/tovu-theme/references/kuinetic-worked-example.md'));
  assert.ok(packed.files.includes('skills/tovu-theme/references/motion.md'));
  const skill = await readFile(path.join(root, 'skills/tovu-theme/SKILL.md'), 'utf8');
  assert.match(skill, /theme_set_page_published/);
  assert.match(skill, /theme_import_local_file/);
  assert.match(skill, /theme_import_file_from_url/);
  assert.match(skill, /apiVersion 2/);
  assert.match(skill, /Inventory first[\s\S]*Before building or re-uploading[\s\S]*library_list[\s\S]*content_read\.media_asset[\s\S]*fs_list_files[\s\S]*Reuse existing assets by slug/);
  assert.doesNotMatch(skill, /\bmedia_list_assets\b/);
  assert.match(skill, /never.*Bash|Never.*Bash/);
  assert.match(skill, /theme list\/read\/search → theme_list_files \/ theme_read_file \(find, startLine, lineCount\)/);
  assert.match(skill, /site\/handoff\/plugin text → fs_list_files \/ fs_read_file/);
  assert.match(skill, /page HTML\/localhost routes → fetch_published_page \(site path, never curl\)/);
  assert.match(skill, /picked-folder copies → files_copy/);
  assert.match(skill, /images → media_view_image/);
  assert.match(skill, /documents → library_list \/ library_read \(text only; PDFs are download-only, so PDF inspection is a Tool gap\)/);
  assert.match(skill, /After ONE "Operation not permitted" or permission refusal, do not retry the same kind of command/);
  assert.match(skill, /even with another shell, flags or path spelling/);
  assert.match(skill, /Switch to the mapped tool; otherwise stop and tell the owner in one line: `Tool gap:/);
  assert.match(skill, /Native fallback gaps are recorded automatically; tool_gaps_list reads that audit/);
  assert.match(skill, /Shell is only for genuine tool gaps: literal paths inside granted roots, no paths computed at run time/);
  assert.match(skill, /no ~\/\.claude\/tool-results or other CLI spill-file reads/);
  assert.match(skill, /Applies to every agent CLI/);
  assert.deepEqual(JSON.parse(await readFile(path.join(root, 'mcp.json'), 'utf8')).mcpServers, {});
});
